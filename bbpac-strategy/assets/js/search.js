/* ==========================================================================
   search.js — simple client-side full-text search across every page.
   ==========================================================================
   Loads /assets/data/search-index.json (an array of records, one per
   section/FAQ item across the whole site) and does a plain substring /
   keyword match — no build step, no external service, works on GitHub
   Pages as static files.

   REGENERATING THE INDEX: the index is generated by
   /tools/build-search-index.py (kept outside the deployed site) which
   walks every .html file, pulls out each <section data-searchable> block's
   heading + text, and writes assets/data/search-index.json. Re-run it any
   time page content changes. See /tools/README.md.
   ========================================================================== */

(function () {
  var input = document.getElementById('site-search-input');
  var resultsBox = document.getElementById('search-results');
  if (!input || !resultsBox) return;

  var INDEX = null;
  var root = window.SITE_ROOT || './';

  fetch(root + 'assets/data/search-index.json')
    .then(function (r) { return r.json(); })
    .then(function (data) { INDEX = data; })
    .catch(function () { INDEX = []; });

  function scoreEntry(entry, terms) {
    var haystack = (entry.title + ' ' + entry.page + ' ' + entry.text).toLowerCase();
    var score = 0;
    terms.forEach(function (t) {
      var idx = haystack.indexOf(t);
      if (idx === -1) return;
      score += (idx < 40 ? 3 : 1);
      // small boost if term is in the title
      if (entry.title.toLowerCase().indexOf(t) !== -1) score += 4;
    });
    return score;
  }

  function render(query) {
    if (!INDEX || query.trim().length < 2) {
      resultsBox.classList.remove('open');
      resultsBox.innerHTML = '';
      return;
    }
    var terms = query.toLowerCase().split(/\s+/).filter(Boolean);
    var scored = INDEX.map(function (entry) {
      return { entry: entry, score: scoreEntry(entry, terms) };
    }).filter(function (s) { return s.score > 0; })
      .sort(function (a, b) { return b.score - a.score; })
      .slice(0, 12);

    if (scored.length === 0) {
      resultsBox.innerHTML = '<div class="result-empty">No matches. Try a different term (e.g. a name, a park number, or a topic like "FAQ").</div>';
    } else {
      resultsBox.innerHTML = scored.map(function (s) {
        var e = s.entry;
        var snippet = e.text.length > 130 ? e.text.slice(0, 130) + '…' : e.text;
        return '<a href="' + root + e.href + '">' + e.title +
          '<div class="result-path">' + e.page + ' — ' + snippet + '</div></a>';
      }).join('');
    }
    resultsBox.classList.add('open');
  }

  input.addEventListener('input', function () { render(input.value); });
  input.addEventListener('focus', function () { if (input.value) render(input.value); });
  document.addEventListener('click', function (e) {
    if (!resultsBox.contains(e.target) && e.target !== input) {
      resultsBox.classList.remove('open');
    }
  });
})();
